// ChatGPT
// ├── Core Overview
// ├── SEO
// ├── Education
// ├── Productivity
// ├── Business
// └── Prompt Engineering
//
// তাই আগে topic select হবে,
// তারপর backend/database থেকে available angle select হবে।
//

export const categoryAndTopicSelector = () => {
    const randomCategory = getRandomItem(categories);

    if (!randomCategory) {
        throw new Error("No category available");
    }

    const cat = randomCategory.name;

    const hasTrending =
        Array.isArray(randomCategory.trendingTopics) &&
        randomCategory.trendingTopics.length > 0;

    const hasNormalTopics =
        Array.isArray(randomCategory.topics) &&
        randomCategory.topics.length > 0;

    if (!hasTrending && !hasNormalTopics) {
        throw new Error(
            `No topics available for category: ${cat}`
        );
    }

    // 50% chance trending topic
    // যদি trending topic না থাকে তাহলে normal topic
    const useTrending =
        hasTrending &&
        Math.random() < 0.5;

    const topic = useTrending
        ? getRandomItem(randomCategory.trendingTopics)
        : getRandomItem(randomCategory.topics);

    if (!topic) {
        throw new Error(
            `No topic available for category: ${cat}`
        );
    }

    return {
        cat,
        topic,
        isTrending: useTrending,
    };
};


